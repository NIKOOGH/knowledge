// ============================================================
// 01_variables.go  变量与常量
// ------------------------------------------------------------
// 核心知识点：
//   1) var 声明方式（显式类型）
//   2) := 短变量声明（只能在函数内）
//   3) 多变量同时赋值
//   4) 常量 + iota
//   5) 命名规则 + 变量零值
//   运行：go run 01_variables.go
// ============================================================

package main

import "fmt"

// ------------------------------------------------------------
// 1. 包级变量（全局）：必须用 var 声明，不能用 :=
// ------------------------------------------------------------

// var 声明：类型写在名字后面（和 Java 相反）
var globalInt int = 100

// 不写类型 → 自动推断（类型推断）
var globalName = "global"

// 多变量声明块：同一 var ( ... ) 打包，减少重复写 var
var (
	cfgHost = "127.0.0.1"
	cfgPort = 3306
	cfgDebug = true
)

// ------------------------------------------------------------
// 2. 常量：const 关键字，不能被修改
// ------------------------------------------------------------
const Pi = 3.1415926

// 批量常量
const (
	StatusOK      = 200
	StatusCreated = 201
	StatusError   = 500
)

// 2.1 iota：常量计数器，每新增一行常量 +1（类似枚举序号）
const (
	LevelDebug = iota // 0
	LevelInfo         // 1
	LevelWarn         // 2
	LevelError        // 3
	LevelFatal        // 4
)

// iota 可以加表达式，实现位运算掩码
const (
	FlagRead   = 1 << iota // 1 (2^0)
	FlagWrite              // 2 (2^1)
	FlagDelete             // 4 (2^2)
)

func main() {
	// ------------------------------------------------------------
	// 3. 函数内局部变量
	// ------------------------------------------------------------

	// 3.1 var 声明 + 显式类型，不赋初值 → 自动使用零值
	//    Go 中没有未初始化变量，零值有明确规则：
	//       数字 → 0，bool → false，string → ""，指针 → nil
	var a int
	var b bool
	var s string
	fmt.Println("零值：a=", a, "b=", b, "s=", s) // 0  false  ""

	// 3.2 var 声明 + 初值，可不写类型（推断）
	var c int = 100
	var d = "hello"
	fmt.Println("显式初值：c=", c, "d=", d)

	// 3.3 := 短变量声明（函数内最常用写法）
	// 规则：左边至少有一个新变量，否则报错；只能在函数/块内使用
	x := 10
	y := "world"
	fmt.Println("短声明：x=", x, "y=", y)

	// 左侧已有变量 + 至少一个新变量时可复用 :=
	// x 已存在，z 是新变量 → 合法，x 实际上是 "=" 赋值
	x, z := 99, "new var"
	fmt.Println("复用 := : x=", x, "z=", z)

	// ------------------------------------------------------------
	// 4. 多变量同时赋值（特别用于交换两个变量）
	// ------------------------------------------------------------
	i, j := 1, 2
	i, j = j, i           // 不需要临时变量，Java 要三行
	fmt.Println("交换后：i=", i, "j=", j)

	// 多返回值接收（见 04_functions.go 的多返回值）
	m, n := 3, 4
	fmt.Println("m=", m, "n=", n)

	// 用 _ 忽略不需要的返回值（类似 void / 占位符）
	// 例：假设某函数返回 (int, error)，我们不要 error
	//     value, _ := someFunc()   ← error 被直接忽略
	_ = 0 // 占位，避免 _ 未使用而报错

	// ------------------------------------------------------------
	// 5. 变量可见性规则（包级才有 public/private 之分）
	// ------------------------------------------------------------
	// 名字首字母大写（如 globalName→GlobalName）= 包外可见（public）
	// 名字首字母小写 = 仅当前包内可见（private）
	// 这是 Go 唯一的访问控制机制：没有 public/private 关键字

	// ------------------------------------------------------------
	// 6. 打印常量
	// ------------------------------------------------------------
	fmt.Println("Pi=", Pi)
	fmt.Println("StatusOK=", StatusOK)
	fmt.Println("日志级别 Debug/Info/Warn/Error/Fatal =",
		LevelDebug, LevelInfo, LevelWarn, LevelError, LevelFatal)
	fmt.Println("读写删标志 = ", FlagRead, FlagWrite, FlagDelete)
}
