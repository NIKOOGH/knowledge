// ============================================================
// 05_pointers.go  指针
// ------------------------------------------------------------
// 核心知识点：
//   1) *T 指针类型；&v 取地址；*p 解引用
//   2) nil 指针
//   3) 值传递 vs 引用传递（指针/切片/Map/通道都是引用语义）
//   4) new() 函数
//   运行：go run 05_pointers.go
// ============================================================

package main

import "fmt"

// ------------------------------------------------------------
// 1. 基本使用：& 取地址，* 解引用
// ------------------------------------------------------------
func basicPtr() {
	x := 10
	p := &x          // p 类型是 *int，指向 x 所在的内存
	fmt.Println("x 的值 =", x)
	fmt.Println("x 的地址 =", p)   // 0xc0000a2000（每次运行不同）
	fmt.Println("*p（解引用）=", *p)

	// 通过指针修改原变量
	*p = 20
	fmt.Println("通过 *p 修改后 x =", x) // x 变成 20
}

// ------------------------------------------------------------
// 2. 用指针实现"函数内修改外部变量"
// ------------------------------------------------------------
// Java 里把对象传入方法修改字段是引用语义，基本类型是值传递。
// Go 里一切都是值传递（拷贝一份），想修改原内容必须传指针。
func swapFail(a, b int) { // 值传递，没效果
	tmp := a
	a = b
	b = tmp
}
func swapOK(a, b *int) { // 传地址，有效
	tmp := *a
	*a = *b
	*b = tmp
}

// ------------------------------------------------------------
// 3. nil 指针
// ------------------------------------------------------------
func nilPtr() {
	var p *int // 指针未初始化 → nil
	fmt.Println("p == nil？", p == nil)

	// *p = 123  // 直接解引用 nil 指针 → runtime panic（空指针）

	// 用 new(T) 可以安全地分配一个 T 的零值，返回 *T
	q := new(int) // q 类型 *int，*q == 0
	fmt.Println("new(int) 返回的 *q =", *q, "地址 =", q)
	*q = 99
	fmt.Println("赋值后 *q =", *q)
}

// ------------------------------------------------------------
// 4. 结构体指针：点号自动解引用
// ------------------------------------------------------------
type User struct {
	Name string
	Age  int
}

func structPtr() {
	u := &User{Name: "Tom", Age: 18}
	// Java 风格：p.field  —— Go 自动解引用指针，不需要 ->
	fmt.Printf("Name=%s Age=%d\n", u.Name, u.Age)
	// 等价于 (*u).Name，但没人会写这么啰嗦
}

// ------------------------------------------------------------
// 5. 值传递 vs 引用语义（重要概念对比）
// ------------------------------------------------------------
type Point struct{ X, Y int }

// 传结构体值：会拷贝整个结构体，改字段对外面没影响
func updateByValue(p Point) {
	p.X = 100
	p.Y = 200
}

// 传指针：引用原对象，直接改
func updateByPtr(p *Point) {
	p.X = 100
	p.Y = 200
}

// 注意：
//   不是"指针叫引用传递、其他叫值传递"这种说法——
//   Go 所有函数调用都是值传递，指针参数传递的是地址的一份复制。
//   我们日常说的"引用语义"，指的是传进去的那一份地址本身指向原对象。

// ------------------------------------------------------------
// 主函数
// ------------------------------------------------------------
func main() {
	fmt.Println("===== 1. 指针基础 =====")
	basicPtr()

	fmt.Println("\n===== 2. swap =====")
	a, b := 1, 2
	swapFail(a, b)
	fmt.Printf("swapFail 后 a=%d b=%d（没变化）\n", a, b)
	swapOK(&a, &b)
	fmt.Printf("swapOK   后 a=%d b=%d（已交换）\n", a, b)

	fmt.Println("\n===== 3. nil / new =====")
	nilPtr()

	fmt.Println("\n===== 4. 结构体指针 =====")
	structPtr()

	fmt.Println("\n===== 5. 值 vs 指针 =====")
	p := Point{1, 2}
	updateByValue(p)
	fmt.Printf("updateByValue 后 p=(%d,%d)\n", p.X, p.Y) // 没变化
	updateByPtr(&p)
	fmt.Printf("updateByPtr   后 p=(%d,%d)\n", p.X, p.Y) // 变了
}
